CREATE TABLE Products (
    ProductID   INT PRIMARY KEY,
    ProductName VARCHAR(50),
    Category    VARCHAR(30),
    Price       INT
);

CREATE TABLE Sales (
    SaleID       INT PRIMARY KEY,
    SaleDate     DATE,
    CustomerName VARCHAR(50),
    City         VARCHAR(30),
    ProductID    INT,
    Quantity     INT,
    FOREIGN KEY (ProductID) REFERENCES Products(ProductID)
);

