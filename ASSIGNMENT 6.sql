CREATE TRIGGER AFTER_INSERT_SALES
AFTER INSERT ON SALES
FOR EACH ROW
BEGIN
    INSERT INTO SALES_LOG
    VALUES (NEW.SALEID, NEW.CUSTOMERNAME, 'SALE ADDED');
END //

