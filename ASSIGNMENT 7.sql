SELECT * FROM PATIENTS;

SELECT DISTINCT DEPARTMENT FROM PATIENTS;

SELECT PATIENT_NAME FROM PATIENTS WHERE PATIENT_NAME LIKE "A%";

SELECT PATIENT_NAME FROM PATIENTS WHERE PATIENT_NAME LIKE "%N";

WITH AVG_TREATMENT_COST AS ( 
SELECT DEPARTMENT , AVG(TREATMENT_COST) AS AVG_COST FROM PATIENTS GROUP BY DEPARTMENT)
SELECT DEPARTMENT FROM AVG_TREATMENT_COST WHERE AVG_COST > 50000;

WITH A AS ( 
SELECT DOCTOR_NAME , COUNT(PATIENT_NAME) AS CNT FROM PATIENTS GROUP BY DOCTOR_NAME ) 
SELECT DOCTOR_NAME FROM A WHERE CNT > 2;

SELECT DEPARTMENT , AVG(TREATMENT_COST) AS AVG_COST FROM PATIENTS GROUP BY DEPARTMENT HAVING AVG(TREATMENT_COST) > 50000;

SELECT PATIENT_NAME , DEPARTMENT , TREATMENT_COST ,
CASE
	WHEN TREATMENT_COST >= 150000 THEN "CRITICAL CARE"
    WHEN TREATMENT_COST >= 50000 THEN "MODERATE"
    ELSE "BASIC"
END AS CATEGORY_COST
FROM PATIENTS;

SELECT PATIENT_NAME , DEPARTMENT , AGE,
CASE 
	WHEN AGE < 18 THEN "CHILD"
    WHEN AGE > 18 AND AGE < 60 THEN "ADULT"
    ELSE "SENIOR"
END AS AGE_GROUP 
FROM PATIENTS;

SELECT PATIENT_NAME, INSURANCE_PROVIDER,
CASE 
	WHEN INSURANCE_PROVIDER IS NULL THEN "SELF PAY"
    ELSE "INSURED"
END AS INSURANCE_STATUS
FROM PATIENTS;

SELECT * FROM PATIENTS WHERE TREATMENT_COST IS NULL;

SELECT PATIENT_NAME , IFNULL(TREATMENT_COST,0) AS UPDATED FROM PATIENTS;

SELECT PATIENT_NAME , COALESCE(EMAIL,PHONE,"NO CONTACT AVAILABLE") AS CONTACT FROM PATIENTS;

WITH B AS (
SELECT DEPARTMENT , AVG(IFNULL(TREATMENT_COST,0)) AS AVG_COST FROM PATIENTS GROUP BY DEPARTMENT)
SELECT DEPARTMENT , AVG_COST ,
CASE
	WHEN AVG_COST>100000 THEN "HIGH REVENUE"
    WHEN AVG_COST>30000 AND AVG_COST<100000 THEN "MEDIUM REVENUE"
    ELSE "LOW REVENUE"
END AS COST 
FROM B;

WITH C AS (
SELECT DEPARTMENT , COUNT(*) AS COUNT_OF_PATIENT FROM PATIENTS WHERE EMAIL IS NULL AND PHONE IS NULL GROUP BY DEPARTMENT )
SELECT DEPARTMENT , COUNT_OF_PATIENT 
FROM C;

WITH D AS ( 
SELECT INSURANCE_PROVIDER , SUM(TREATMENT_COST) AS TOTAL_COST FROM PATIENTS GROUP BY INSURANCE_PROVIDER )
SELECT INSURANCE_PROVIDER , IFNULL(TOTAL_COST , 0 ) , 
CASE 
	WHEN INSURANCE_PROVIDER IS NULL THEN "SELF PAY" 
    ELSE "INSURED"
END AS N
FROM D;

