WITH F AS (
SELECT DEPARTMENT , COUNT(*) AS TOTAL_PATIENTS , IFNULL(SUM(TREATMENT_COST),0) AS TOTAL_TREATMENT_COST , SUM(ISNULL(TREATMENT_COST)) AS MISSING_TREATMENT_COST 
FROM PATIENTS GROUP BY DEPARTMENT)
SELECT DEPARTMENT , TOTAL_PATIENTS , TOTAL_TREATMENT_COST , MISSING_TREATMENT_COST ,
CASE 
	WHEN TOTAL_TREATMENT_COST > 150000 THEN "HIGH REVENUE"
    WHEN TOTAL_TREATMENT_COST > 100000 THEN "MEDIUM REVENUE"
    ELSE "LOW REVENUE"
END AS REVENUE_LEVEL 
FROM F;

